    canvas.setLineWidth(0.5)
    canvas.line(LEFT_M, PAGE_H - TOP_M * 0.55 - 4,
                PAGE_W - RIGHT_M, PAGE_H - TOP_M * 0.55 - 4)

    # Footer
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(LEFT_M, BOTTOM_M * 0.55 + 14,
                PAGE_W - RIGHT_M, BOTTOM_M * 0.55 + 14)
    canvas.setFont('FreeSerif-Italic', 8)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(LEFT_M, BOTTOM_M * 0.55, 'Confidential — Internal Use Only')
    # Page number with +1 offset for merged cover
    page_num = canvas.getPageNumber() + 1
    canvas.drawRightString(PAGE_W - RIGHT_M, BOTTOM_M * 0.55, f'Page {page_num}')
    canvas.restoreState()


